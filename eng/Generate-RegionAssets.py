"""Generate packaged flags and eight-language country names from pinned upstream sources.

Usage: python eng/Generate-RegionAssets.py --source-directory <downloaded sources>
Requires CairoSVG 2.9 and Pillow; generated assets have no runtime network dependency.
Source files are independently verified against RegionAssets.sources.json before processing.
"""
from pathlib import Path
import argparse
import hashlib
import io
import json
import zipfile
import cairosvg
from PIL import Image

parser=argparse.ArgumentParser()
parser.add_argument('--source-directory',type=Path,required=True)
args=parser.parse_args()
repo=Path(__file__).resolve().parent.parent
pins=json.loads((repo/'eng/RegionAssets.sources.json').read_text(encoding='utf-8'))
source=args.source_directory.resolve()
for entry in pins['files']:
    raw=(source/entry['name']).read_bytes()
    if len(raw)!=entry['length'] or hashlib.sha256(raw).hexdigest()!=entry['sha256']:
        raise ValueError('Pinned source differs: '+entry['name'])

archive=zipfile.ZipFile(source/'flags.zip')
prefix=archive.namelist()[0].split('/')[0]+'/'
countries=json.loads(archive.read(prefix+'country.json'))
countries=sorted([c for c in countries if c['iso'] or c['code'] in ('eu','xk')],key=lambda c:c['code'])
assert len(countries)==251
locales=['zh-Hans','zh-Hant','en','ru','fr','de','fa','ko']
names={locale:json.loads((source/(locale+'.json')).read_text(encoding='utf-8'))['main'][locale]['localeDisplayNames']['territories'] for locale in locales}
asset_root=repo/'ClashSharp/ClashSharp/Assets/Flags'
rows=[]
inventory=[]
for country in countries:
    code=country['code']
    svg=archive.read(prefix+country['flag_4x3'])
    raster=cairosvg.svg2png(bytestring=svg,output_width=128,output_height=96)
    image=Image.open(io.BytesIO(raster)).convert('RGBA')
    target=asset_root/(code+'.png')
    image.save(target,format='PNG',optimize=True)
    labels=[names[locale].get(code.upper(),country['name']) for locale in locales]
    rows.append('        ("'+code.upper()+'", ['+', '.join(json.dumps(label,ensure_ascii=False) for label in labels)+']),')
    inventory.append({'code':code.upper(),'iso':country['iso'],'file':code+'.png','sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
data='''// Generated by eng/Generate-RegionAssets.py from pinned flag-icons and Unicode CLDR sources.
namespace ClashSharp.Service;

internal static partial class RegionCatalog
{
    private static (string Code, string[] Names)[] CreateCountryData() =>
    [
'''+ '\n'.join(rows)+'''
    ];
}
'''
(repo/'ClashSharp/ClashSharp/Service/RegionCatalog.Data.cs').write_text(data,encoding='utf-8',newline='\n')
(asset_root/'manifest.json').write_text(json.dumps({'schema':1,'flagIconsCommit':pins['flagsCommit'],'cldrCommit':pins['cldrCommit'],'width':128,'height':96,'countries':inventory},ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')

catalog_path=repo/'ClashSharp/Installer/ThirdParty/catalog.json'
catalog=json.loads(catalog_path.read_text(encoding='utf-8-sig'))
for original,target_name in [('flags-LICENSE','flag-icons-license.txt'),('cldr-LICENSE','unicode-cldr-license.txt')]:
    entry=next(e for e in pins['files'] if e['name']==original)
    raw=(source/original).read_bytes()
    (catalog_path.parent/target_name).write_bytes(raw)
    catalog['documents']=[item for item in catalog['documents'] if item['file']!=target_name]
    catalog['documents'].append({'file':target_name,'sourceUrl':entry['url'],'length':len(raw),'sha256':hashlib.sha256(raw).hexdigest()})
catalog_path.write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
print('Generated',len(countries),'flags at128x96 and country names in8languages')
